def load_criterion_json(criterion_dir):
    """Load all estimates.json from criterion output."""
    data = {}

    # Multi-scenario: group/bench/scenario/new/estimates.json
    for path in glob.glob(f"{criterion_dir}/*/*/*/*/estimates.json"):
        if "/new/" not in path:
            continue
        parts = path.replace(criterion_dir + "/", "").split("/")
        if len(parts) == 5:
            bench_group = parts[0]
            bench_name = parts[1]
            scenario = parts[2]
            key = (bench_group, bench_name, scenario)

            with open(path) as f:
                est = json.load(f)

            data[key] = {
                "median_ns": est["median"]["point_estimate"],
                "mean_ns": est["mean"]["point_estimate"],
                "p_low_ns": est["median"]["confidence_interval"]["lower_bound"],
                "p_high_ns": est["median"]["confidence_interval"]["upper_bound"],
            }

    # Single-scenario: group/bench/new/estimates.json
    for path in glob.glob(f"{criterion_dir}/*/*/*/estimates.json"):
        if "/new/" not in path:
            continue
        parts = path.replace(criterion_dir + "/", "").split("/")
        if len(parts) == 4:
            bench_group = parts[0]
            bench_name = parts[1]
            key = (bench_group, bench_name, "default")
            with open(path) as f:
                est = json.load(f)
            data[key] = {
                "median_ns": est["median"]["point_estimate"],
                "mean_ns": est["mean"]["point_estimate"],
                "p_low_ns": est["median"]["confidence_interval"]["lower_bound"],
                "p_high_ns": est["median"]["confidence_interval"]["upper_bound"],
            }

    return data


def main():
    criterion_data = load_criterion_json(CRITERION_DIR)

    output = io.StringIO()
    writer = csv.DictWriter(output, fieldnames=COLUMNS)
    writer.writeheader()

    row_count = 0
    missing_count = 0
    for algo in ALGORITHMS:
        crit_group = algo["criterion_group"]
        default_crit_bench = algo["criterion_bench"]
        scenarios = algo["scenario_sizes"]

        for item in scenarios:
            # Support 2-tuple (standard) or 4-tuple (override) format
            if len(item) == 2:
                scenario_name, input_size = item
                crit_bench = default_crit_bench
                crit_scenario = scenario_name
            elif len(item) == 4:
                scenario_name, input_size, crit_bench, crit_scenario = item
            else:
                raise ValueError(f"Invalid scenario_sizes format: {item}")

            key = (crit_group, crit_bench, crit_scenario)
            timing = criterion_data.get(key, {})

            if not timing:
                missing_count += 1
                print(f"# MISS: {key}", file=sys.stderr)

            row = {
                "algorithm_id": algo["algorithm_id"],
                "algorithm_name": algo["algorithm_name"],
                "variant": algo["variant"],
                "module_path": algo["module_path"],
                "source_file": algo["source_file"],
                "group": algo["group"],
                "goal": algo["goal"],
                "origin": algo["origin"],
                "origin_detail": algo["origin_detail"],
                "hot_path": algo["hot_path"],
                "hot_path_location": algo["hot_path_location"],
                "calls_per_request": algo["calls_per_request"],
                "tier": algo["tier"],
                "tier_rationale": algo["tier_rationale"],
                "has_optimized_variant": algo["has_optimized_variant"],
                "optimized_variant_id": algo["optimized_variant_id"],
                "is_optimized_variant": algo["is_optimized_variant"],
                "replaces_algorithm_id": algo["replaces_algorithm_id"],
                "bench_target": algo["bench_target"],
                "bench_scenario": scenario_name,
                "input_size_bytes": input_size,
                "median_ns": f"{timing['median_ns']:.2f}" if timing else "",
                "mean_ns": f"{timing['mean_ns']:.2f}" if timing else "",
                "p_low_ns": f"{timing['p_low_ns']:.2f}" if timing else "",
                "p_high_ns": f"{timing['p_high_ns']:.2f}" if timing else "",
                "complexity": algo["complexity"],
                "memory_profile": algo["memory_profile"],
                "compile_weight": algo["compile_weight"],
                "notes": algo["notes"],
            }
            writer.writerow(row)
            row_count += 1

    print(output.getvalue(), end="")
    print(f"# Generated {row_count} rows from {len(ALGORITHMS)} algorithms ({missing_count} missing timing)", file=sys.stderr)


if __name__ == "__main__":
    main()
